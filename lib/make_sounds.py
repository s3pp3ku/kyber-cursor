#!/usr/bin/python3
"""Kyber's default sound pack, synthesized from scratch.

Every sound here is generated by this script from sine waves and filtered
noise. Nothing is sampled or copied from any film, game or recording, so the
pack is original, licensed like the rest of the project (MIT), and safe to
generate and share. Standard library only.

    make_sounds.py OUTPUT_DIR      writes OUTPUT_DIR/{ignite,off,clash}/*.wav

Same output every run (fixed seeds). Names follow Kyber's rule for clashes: a
file called "2-*" already holds two strikes and plays once; any other clash
file is played twice by the listener.
"""
import math
import random
import struct
import sys
import wave
from pathlib import Path

SR = 44100
PEAK = 0.85


def envelope_exp(t, tau):
    return math.exp(-t / tau)


def hum(n, f0_fn, depth=0.6, vib_hz=7.0, vib_depth=0.012, partials=6):
    """A buzzing 'engine' tone: a few harmonics with a slight wobble."""
    out = []
    phase = 0.0
    for i in range(n):
        t = i / SR
        f = f0_fn(t) * (1.0 + vib_depth * math.sin(2 * math.pi * vib_hz * t))
        phase += 2 * math.pi * f / SR
        v = 0.0
        for k in range(1, partials + 1):
            v += math.sin(k * phase) / (k ** 1.15)
        # slow beating between the harmonics, so it shimmers a little
        v *= 1.0 - depth * 0.25 * (1.0 + math.sin(2 * math.pi * 2.3 * t))
        out.append(v * 0.45)
    return out


def swept_noise(n, fc_fn, q, rng):
    """White noise through a resonant band-pass whose center frequency moves."""
    low = band = 0.0
    out = []
    q1 = 1.0 / q
    for i in range(n):
        t = i / SR
        f = 2.0 * math.sin(math.pi * min(fc_fn(t), SR / 6.0) / SR)
        x = rng.uniform(-1.0, 1.0)
        low += f * band
        high = x - low - q1 * band
        band += f * high
        out.append(band)
    return out


def mix(*tracks):
    n = max(len(t) for t in tracks)
    out = [0.0] * n
    for t in tracks:
        for i, v in enumerate(t):
            out[i] += v
    return out


def scale(track, gain):
    return [v * gain for v in track]


def shape(track, fn):
    return [v * fn(i / SR) for i, v in enumerate(track)]


def normalize(track, peak=PEAK):
    m = max(abs(v) for v in track) or 1.0
    return [v * peak / m for v in track]


def fade_edges(track, fade_in=0.004, fade_out=0.03):
    n = len(track)
    a = int(SR * fade_in)
    b = int(SR * fade_out)
    out = list(track)
    for i in range(min(a, n)):
        out[i] *= i / a
    for i in range(min(b, n)):
        out[n - 1 - i] *= i / b
    return out


def ignite(seed, base=82.0, length=1.3):
    """A blade powering on: a snap, a rising whoosh, then a settling hum."""
    rng = random.Random(seed)
    n = int(SR * length)
    glide = lambda t: base * (0.55 + 0.45 * (1 - math.exp(-t / 0.18)))
    h = hum(n, glide)
    h = shape(h, lambda t: min(1.0, t / 0.05) * (1.0 if t < length - 0.3 else math.exp(-(t - (length - 0.3)) / 0.10)))
    w = swept_noise(n, lambda t: 260 * math.exp(t * 5.2) if t < 0.5 else 3500, 4.0, rng)
    w = shape(w, lambda t: (min(1.0, t / 0.06) * math.exp(-max(0.0, t - 0.5) / 0.25)) * 0.55)
    snap = [rng.uniform(-1, 1) * math.exp(-(i / SR) / 0.012) for i in range(int(SR * 0.05))]
    return normalize(fade_edges(mix(h, w, scale(snap, 0.7))))


def off(seed, base=82.0, length=0.8):
    """A blade powering off: the hum drops in pitch and a whoosh falls away."""
    rng = random.Random(seed)
    n = int(SR * length)
    fall = lambda t: base * (0.45 + 0.55 * math.exp(-t / 0.2))
    h = hum(n, fall)
    h = shape(h, lambda t: math.exp(-t / 0.22))
    w = swept_noise(n, lambda t: 2600 * math.exp(-t * 4.5) + 160, 4.0, rng)
    w = shape(w, lambda t: math.exp(-t / 0.2) * 0.5)
    return normalize(fade_edges(mix(h, w), fade_out=0.08))


def clash(seed, length=0.7):
    """One strike: a noise crack with metallic ringing over a swelling hum."""
    rng = random.Random(seed)
    n = int(SR * length)
    crack = [rng.uniform(-1, 1) * math.exp(-(i / SR) / 0.045) for i in range(n)]
    ring = [0.0] * n
    partials = [rng.uniform(1100, 1500), rng.uniform(1800, 2300), rng.uniform(2700, 3400), rng.uniform(4100, 4900)]
    for k, f in enumerate(partials):
        tau = 0.22 - k * 0.04
        amp = 0.5 / (k + 1)
        ph = rng.uniform(0, 6.28)
        for i in range(n):
            t = i / SR
            ring[i] += amp * math.sin(2 * math.pi * f * t + ph) * math.exp(-t / tau)
    h = hum(n, lambda t: 96.0 * (1.0 + 0.15 * math.exp(-t / 0.1)))
    h = shape(h, lambda t: 0.8 * math.exp(-t / 0.28))
    return normalize(fade_edges(mix(scale(crack, 1.0), scale(ring, 0.8), h)))


def double_clash(seed_a, seed_b, gap=0.14):
    a = clash(seed_a, 0.6)
    b = clash(seed_b, 0.7)
    off_samples = int(SR * gap)
    out = [0.0] * (off_samples + len(b))
    for i, v in enumerate(a):
        out[i] += v
    for i, v in enumerate(b):
        out[off_samples + i] += v * 0.95
    return normalize(fade_edges(out))


def save(path, track):
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(b''.join(struct.pack('<h', int(max(-1.0, min(1.0, v)) * 32767)) for v in track))


def main(out_dir):
    out = Path(out_dir)
    for i, (seed, base) in enumerate(((11, 78.0), (23, 86.0), (37, 94.0)), start=1):
        save(out / 'ignite' / f'ignite-{i}.wav', ignite(seed, base))
    for i, (seed, base) in enumerate(((41, 80.0), (53, 90.0)), start=1):
        save(out / 'off' / f'off-{i}.wav', off(seed, base))
    for i, seed in enumerate((61, 73, 89), start=1):
        save(out / 'clash' / f'clash-{i}.wav', clash(seed))
    save(out / 'clash' / '2-clash-1.wav', double_clash(97, 101))
    save(out / 'clash' / '2-clash-2.wav', double_clash(103, 107, gap=0.18))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit('usage: make_sounds.py OUTPUT_DIR')
    main(sys.argv[1])
