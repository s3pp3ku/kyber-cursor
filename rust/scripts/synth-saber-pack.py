#!/usr/bin/python3
"""Kyber's fully synthesized sound pack: no recordings, no ElevenLabs takes.

The held hum is the owner-approved four-layer procedural blend (2026-10-17,
generated by rust/crates/kyber-core/examples/hum_layers.rs). Every other role
is built from that hum plus one new ingredient the earlier synthetic drafts
lacked: a bright electrical "sizzle" (1-10 kHz shaped noise with crackle,
buzzed at the hum's own 92 Hz). Reference measurements show that sizzle carries
most of the energy in a lightsaber's power-up, power-down, swing and clash.

    synth-saber-pack.py OUT_DIR [--hum full-hum.wav]

Writes OUT_DIR/{hum,ignite,off,swipe,clash}/*.wav and OUT_DIR/demo.wav.
Deterministic (fixed seeds). Needs numpy; maintainer tool, not a runtime dep.

Runtime contracts this file must respect (rust/crates/kyber-ignite/src/audio.rs,
rust/crates/kyber-core/src/sound_pack.rs):
- RecordedHum skips 0.3 s at each end of the hum file and starts at that point.
- The hum enters 0.15 s before the ignition ends, with a linear fade-in. So the
  ignition's last 0.15 s is the same hum samples, fading out linearly: the two
  sum back to exactly one.
- Swipes are played at 2.4x gain while the hum ducks to 0.08, so a swipe file
  carries its own hum at 1/2.4 level at its edges.
- Clashes play on top of the undimmed hum.
"""
import argparse
import hashlib
import json
import wave
from pathlib import Path

import numpy as np

SR = 44100
ROOT = Path(__file__).resolve().parents[2]
APPROVED_HUM = ROOT / "test-artifacts/archive/hum-layers-crackle-2026-10-17/full-hum.wav"
APPROVED_SHA = "1303b079c6b09d3e8a93f56bfcca4836ad7419cf0e54a229c2bf7a170976346b"
HUM_HZ = 92.3
EDGE = int(0.3 * SR)  # RecordedHum's trimmed edge
HANDOFF = int(0.15 * SR)  # hum fade-in under the ignition's tail
SWIPE_GAIN = 2.4


def load(path):
    with wave.open(str(path)) as w:
        assert (w.getnchannels(), w.getsampwidth(), w.getframerate()) == (1, 2, SR), path
        return np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(np.float64) / 32768


def save(path, x):
    path.parent.mkdir(parents=True, exist_ok=True)
    pcm = np.round(np.clip(x, -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


RUNTIME_OVERLAP = SR * 8 // 100  # RecordedHum's loop blend


class Hum:
    """The approved hum as a seamless loop, readable at any fractional position
    (wrapping). Position 0 is where the runtime starts playing.

    The approved file is a 12 s audition with fades, and its end is ~2 dB
    quieter than its start, so looping it as-is steps in level every pass.
    Here the body is folded with a long equal-power crossfade (its layers drift
    in phase, so they add like uncorrelated signals)."""

    def __init__(self, samples, fold=SR):
        body = samples[EDGE:len(samples) - EDGE]
        loop = body[fold:].copy()
        k = np.linspace(0, np.pi / 2, fold)
        loop[-fold:] = body[-fold:] * np.cos(k) + body[:fold] * np.sin(k)
        self.loop = loop

    def read(self, positions):
        n = len(self.loop)
        p = np.mod(np.asarray(positions, dtype=np.float64), n)
        i = p.astype(np.int64)
        f = p - i
        return self.loop[i] * (1 - f) + self.loop[(i + 1) % n] * f

    def file(self):
        """The hum WAV for the pack. RecordedHum trims EDGE from each end and
        blends its last 80 ms into its first; repeating the first 80 ms at the
        end makes that blend an identity, so the runtime loop is seamless."""
        loop = self.loop
        return np.concatenate([loop[-EDGE:], loop, loop[:RUNTIME_OVERLAP], loop[RUNTIME_OVERLAP:RUNTIME_OVERLAP + EDGE]])

    @property
    def rms(self):
        return float(np.sqrt(np.mean(self.loop ** 2)))


def t_axis(seconds):
    return np.arange(int(seconds * SR)) / SR


def smooth(x, k):
    return 0.5 - 0.5 * np.cos(np.pi * np.clip(x, 0, 1)) if k else np.clip(x, 0, 1)


def positions_from_rate(rate, end_position):
    """Hum read positions for a varispeed curve, pinned so the final sample
    lands on end_position. Rate 1 is the approved pitch."""
    pos = np.cumsum(rate)
    return pos - pos[-1] + end_position


def crackle(n, density, rng, decay_ms=(0.8, 3.5)):
    """Dense, sparse-ish electrical discharges as an amplitude process."""
    out = np.zeros(n)
    hits = rng.random(n) < density / SR
    idx = np.flatnonzero(hits)
    amps = rng.uniform(0.3, 1.0, len(idx))
    taus = rng.uniform(*decay_ms, len(idx)) * SR / 1000
    for i, a, tau in zip(idx, amps, taus):
        m = min(n - i, int(tau * 6))
        out[i:i + m] += a * np.exp(-np.arange(m) / tau)
    return out


def sizzle(n, centre, width, rng, density=900.0, buzz=0.55):
    """Bright electrical hiss. centre/width are per-sample arrays in Hz; the
    spectrum is shaped frame by frame, then crackle and a 92 Hz buzz gate are
    applied so it reads as part of the blade, not as air."""
    fft, hop = 1024, 256
    frames = n // hop + 4
    freqs = np.fft.rfftfreq(fft, 1 / SR)
    window = np.hanning(fft)
    out = np.zeros(frames * hop + fft)
    norm = np.zeros_like(out)
    white = rng.standard_normal(len(out))
    for f in range(frames):
        at = min(f * hop + fft // 2, n - 1)
        c, w = centre[at], width[at]
        mag = np.exp(-0.5 * (np.log2(np.maximum(freqs, 1) / c) / w) ** 2)
        seg = np.fft.irfft(np.fft.rfft(white[f * hop:f * hop + fft] * window) * mag)
        out[f * hop:f * hop + fft] += seg * window
        norm[f * hop:f * hop + fft] += window ** 2
    hiss = (out / np.maximum(norm, 1e-6))[:n]
    hiss /= np.sqrt(np.mean(hiss ** 2)) + 1e-12
    t = np.arange(n) / SR
    gate = (1 - buzz) + buzz * np.abs(np.sin(np.pi * HUM_HZ * t)) ** 2
    spikes = crackle(n, density, rng)
    texture = hiss * gate * (0.45 + 0.9 * spikes / (np.sqrt(np.mean(spikes ** 2)) + 1e-12))
    return texture / (np.sqrt(np.mean(texture ** 2)) + 1e-12)


def db(x):
    return 10 ** (x / 20)


def soft_limit(x, ceiling):
    return ceiling * np.tanh(x / ceiling)


# ---------------------------------------------------------------- the roles


def ignite(hum, seed, seconds=1.05, start_rate=0.62, rise=0.28, sizzle_db=4.0, sizzle_tau=0.30):
    """Snap, then the blade extends: hum pitch rises into place while a bright
    sizzle (also rising) flares and decays. Ends as the plain hum."""
    rng = np.random.default_rng(seed)
    t = t_axis(seconds)
    n = len(t)
    # Pitch goes up: ease-out from start_rate to 1.
    k = np.clip(t / rise, 0, 1)
    rate = start_rate + (1 - start_rate) * (1 - (1 - k) ** 2)
    # The last HANDOFF samples are hum positions 0..HANDOFF, the runtime's start.
    pos = positions_from_rate(rate, HANDOFF - 1)
    body = hum.read(pos)
    level = 0.35 + 0.65 * smooth(t / 0.22, True)
    surge = 1 + 0.35 * np.exp(-np.maximum(t - 0.12, 0) / 0.25) * smooth(t / 0.12, True)
    voice = body * level * surge
    # Sizzle: centre climbs 1.6 -> 3.8 kHz, flares in 12 ms, then decays.
    centre = 1600 + 2200 * smooth(t / 0.25, True)
    width = np.full(n, 0.9)
    env = smooth(t / 0.012, False) * np.exp(-np.maximum(t - 0.05, 0) / sizzle_tau)
    hiss = sizzle(n, centre, width, rng) * env * hum.rms * db(sizzle_db)
    # Snap: a few milliseconds of broadband crack plus a low thump.
    snap_env = np.exp(-t / 0.004) * (t < 0.03)
    snap = rng.standard_normal(n) * snap_env * hum.rms * db(8)
    snap += np.sin(2 * np.pi * 70 * t) * np.exp(-t / 0.035) * hum.rms * db(3)
    x = voice + hiss + snap
    # Hand-over: last HANDOFF samples fade out linearly (the hum fades in linearly).
    fade = np.ones(n)
    fade[-HANDOFF:] = np.linspace(1, 0, HANDOFF)
    x[-HANDOFF:] = body[-HANDOFF:]  # nothing but the hum under the join
    return soft_limit(x * fade, 0.95)


def power_off(hum, seed, seconds=0.85, end_rate=0.42, sizzle_db=0.0):
    """The opposite of the ignition: starts as the hum at full level, the
    pitch falls away while a falling sizzle flares and the blade retracts."""
    rng = np.random.default_rng(seed)
    t = t_axis(seconds)
    n = len(t)
    k = np.clip(t / (seconds * 0.85), 0, 1)
    rate = 1 - (1 - end_rate) * k ** 1.6
    pos = positions_from_rate(rate, int(rng.uniform(1, 6) * SR) + len(t))
    level = 1 - smooth((t - 0.10) / (seconds - 0.10), True)
    voice = hum.read(pos) * level
    centre = 3800 - 2300 * smooth(t / seconds, True)
    width = np.full(n, 0.9)
    env = smooth((t - 0.02) / 0.10, True) * np.exp(-np.maximum(t - 0.12, 0) / 0.22)
    hiss = sizzle(n, centre, width, rng) * env * hum.rms * db(sizzle_db)
    x = voice + hiss
    tail = int(0.03 * SR)
    x[-tail:] *= np.linspace(1, 0, tail)
    return soft_limit(x, 0.95)


def swipe(hum, seed, seconds=0.62, peak_at=0.26, swell_db=6.0, bend=0.05):
    """A swing: the hum swells and brightens and bends in pitch, like the blade
    passing the listener. Carries its own hum (the live hum ducks under it)."""
    rng = np.random.default_rng(seed)
    t = t_axis(seconds)
    n = len(t)
    bell = np.exp(-0.5 * ((t - peak_at) / (seconds * 0.17)) ** 2)
    rate = 1 + bend * (bell - 0.5 * np.exp(-0.5 * ((t - peak_at - 0.12) / 0.07) ** 2))
    pos = positions_from_rate(rate, int(rng.uniform(1, 9) * SR))
    voice = hum.read(pos) * (1 + (db(swell_db) - 1) * bell)
    centre = 1800 + 1600 * bell
    width = np.full(n, 0.8)
    hiss = sizzle(n, centre, width, rng, density=600, buzz=0.7) * bell ** 1.4 * hum.rms * db(swell_db - 4)
    x = (voice + hiss) / SWIPE_GAIN
    edge = int(0.02 * SR)
    x[:edge] *= np.linspace(0, 1, edge)
    x[-edge:] *= np.linspace(1, 0, edge)
    return soft_limit(x, 0.41)


def clash(hum, seed, seconds=0.75, crack_db=10.0, sizzle_db=5.0, ring=(1240.0, 2910.0)):
    """A strike, on top of the running hum: hard crack, a burst of crackling
    sizzle, a short metallic ring and a pitched surge of the blade itself."""
    rng = np.random.default_rng(seed)
    t = t_axis(seconds)
    n = len(t)
    crack = rng.standard_normal(n) * np.exp(-t / 0.018) * hum.rms * db(crack_db)
    crack *= smooth(t / 0.0015, False)
    centre = 3200 - 900 * smooth(t / 0.4, True)
    width = np.full(n, 1.1)
    env = smooth(t / 0.004, False) * np.exp(-t / 0.16)
    hiss = sizzle(n, centre, width, rng, density=2200, buzz=0.4) * env * hum.rms * db(sizzle_db)
    metal = sum(np.sin(2 * np.pi * f * t + rng.uniform(0, 6.28)) * np.exp(-t / tau)
                for f, tau in zip(ring, (0.09, 0.05))) * hum.rms * db(-2)
    rate = 1 - 0.08 * np.exp(-t / 0.08)
    pos = positions_from_rate(rate, int(rng.uniform(1, 9) * SR))
    surge = hum.read(pos) * 0.9 * np.exp(-t / 0.22) * smooth(t / 0.003, False)
    x = crack + hiss + metal + surge
    tail = int(0.05 * SR)
    x[-tail:] *= np.linspace(1, 0, tail)
    return soft_limit(x, 0.95)


# ---------------------------------------------------------------- demo


def demo(hum, ign, off, swp, clh):
    """What a user hears: press, hold, swing, clash, release. Mixes exactly as
    the runtime does (hum entry, swipe duck, 2.4x swipe gain, and the hum's
    20 ms release running under the start of the power-down)."""
    total = int(8.0 * SR)
    out = np.zeros(total)
    out[:len(ign)] += ign
    start = len(ign) - HANDOFF
    rel = int(0.02 * SR)
    release = int(6.6 * SR) + rel
    held = np.arange(release - start)
    body = hum.read(held)
    fade_in = np.minimum(held / HANDOFF, 1)
    duck = np.ones(len(held))
    swing_at = int(2.6 * SR) - start
    duck_target = np.ones(len(held))
    duck_target[swing_at:swing_at + len(swp)] = 0.08
    g = 1.0
    for i in range(len(held)):  # the runtime's one-pole duck smoother
        g += (duck_target[i] - g) * 0.0015
        duck[i] = g
    held_out = body * fade_in * duck
    held_out[-rel:] *= 0.5 + 0.5 * np.cos(np.pi * np.arange(rel) / rel)
    out[start:release] += held_out
    out[start + swing_at:start + swing_at + len(swp)] += swp * SWIPE_GAIN
    c = int(4.4 * SR)
    out[c:c + len(clh)] += clh
    out[release - rel:release - rel + len(off)] += off
    return soft_limit(out, 0.98)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("out", type=Path)
    p.add_argument("--hum", type=Path, default=APPROVED_HUM)
    a = p.parse_args()
    raw = a.hum.read_bytes()
    if a.hum == APPROVED_HUM and hashlib.sha256(raw).hexdigest() != APPROVED_SHA:
        raise SystemExit("approved hum hash mismatch; refusing to build on a different hum")
    samples = load(a.hum)
    hum = Hum(samples)
    out = a.out
    sounds = {
        "hum/kyber-hum.wav": hum.file(),
        "ignite/kyber-ignite-1.wav": ignite(hum, 11),
        "ignite/kyber-ignite-2.wav": ignite(hum, 12, seconds=0.95, start_rate=0.55, rise=0.22, sizzle_tau=0.24),
        "off/kyber-off-1.wav": power_off(hum, 21),
        "off/kyber-off-2.wav": power_off(hum, 22, seconds=0.75, end_rate=0.5),
        "swipe/kyber-swipe-1.wav": swipe(hum, 31),
        "swipe/kyber-swipe-2.wav": swipe(hum, 32, seconds=0.55, peak_at=0.22, bend=-0.04),
        "clash/kyber-clash-1.wav": clash(hum, 41),
        "clash/kyber-clash-2.wav": clash(hum, 42, ring=(1460.0, 3370.0), crack_db=11.0),
    }
    for name, x in sounds.items():
        save(out / name, x)
    d = demo(hum, sounds["ignite/kyber-ignite-1.wav"], sounds["off/kyber-off-1.wav"],
             sounds["swipe/kyber-swipe-1.wav"], sounds["clash/kyber-clash-1.wav"])
    save(out / "demo.wav", d)
    manifest = {
        "id": "kyber-synth-v1",
        "source": "Fully procedural. Hum: approved hum_layers.rs blend; others: synth-saber-pack.py",
        "hum_sha256": hashlib.sha256(raw).hexdigest(),
        "files": {n: round(len(x) / SR, 3) for n, x in sounds.items()},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {len(sounds)} sounds and demo.wav to {out}")


if __name__ == "__main__":
    main()
